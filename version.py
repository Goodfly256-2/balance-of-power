def _ver_tuple(v):
    try:
        return tuple(int(p) for p in str(v).strip().split("."))
    except ValueError:
        return (0,)


def check_updates(timeout=4.0):
    """Спрашивает сервер: есть ли версия новее текущей.

    Возвращает словарь:
      {"available": bool, "remote": str|None, "url": str, "notes": str,
       "error": str|None}
    Никогда не бросает исключений — любые проблемы сети превращаются
    в {"available": False, "error": "..."}.
    """
    try:
        with urllib.request.urlopen(UPDATE_URL, timeout=timeout) as resp:
            data = json.loads(resp.read().decode("utf-8"))
    except Exception as e:  # нет сети, нет файла, кривой JSON — всё сюда
        return {"available": False, "remote": None, "url": UPDATE_URL,
                "notes": "", "error": str(e)}
    remote = str(data.get("version", "")).strip()
    url = str(data.get("url", "") or UPDATE_URL)
    notes = str(data.get("notes", ""))
    available = bool(remote) and _ver_tuple(remote) > _ver_tuple(VERSION)
    return {"available": available, "remote": remote or None, "url": url,
            "notes": notes, "error": None}
